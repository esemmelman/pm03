// Optional DOM smoke check: SOLO_JSDOM points to a jsdom installation.
const {JSDOM}=require(process.env.SOLO_JSDOM||'jsdom');
const fs=require('node:fs');
const dom=new JSDOM(fs.readFileSync('index.html','utf8'),{url:'http://localhost',runScripts:'outside-only'}),w=dom.window;
w.HTMLDialogElement.prototype.showModal=function(){this.open=true};
w.HTMLDialogElement.prototype.close=function(){this.open=false};
w.eval(fs.readFileSync('app.js','utf8')+'\n'+fs.readFileSync('tutorial.js','utf8'));
const $=s=>w.document.querySelector(s),assert=(ok,msg)=>{if(!ok)throw Error(msg)};
assert(w.document.querySelectorAll('.task').length===5,'seed Today view');
$('#quick').value='QA capture';$('#quickForm').dispatchEvent(new w.Event('submit',{cancelable:true}));
assert(w.document.querySelectorAll('.task').length===6,'capture');
$('.task-name').click();$('#taskName').value='Updated title';$('#taskForm').dispatchEvent(new w.Event('submit',{cancelable:true}));
assert(w.document.body.textContent.includes('Updated title'),'edit');$('.check').click();
assert(JSON.parse(w.localStorage.getItem('solo-desk-v1')).tasks.find(t=>t.title==='Updated title').done,'completion persisted');
$('#search').value='QA capture';$('#search').dispatchEvent(new w.Event('input'));
assert(w.document.querySelectorAll('.task').length===1,'search');$('#boardView').click();
assert(w.document.querySelectorAll('.board-column').length===2,'board');$('#startTimer').click();
assert($('#startTimer').textContent.includes('Pause'),'timer start');$('#startTimer').click();
assert($('#startTimer').textContent.includes('Resume'),'timer pause');$('#resetTimer').click();
assert($('#timer').textContent==='25:00','timer reset');
$('#tutorialToggle').click();assert(!$('#tutorial').hidden,'tutorial opens');
const before=JSON.parse(w.localStorage.getItem('solo-desk-v1')).tasks.length;
$('#lessonAction').click();let stored=JSON.parse(w.localStorage.getItem('solo-desk-v1'));
assert(stored.tasks.length===before+14,'example adds fourteen tasks');
assert(stored.projects.filter(p=>p.id==='school-carnival-example').length===1,'example project');
assert(stored.projects.find(p=>p.id==='school-carnival-example').notes.includes('08:30'),'run sheet');
$('#lessonAction').click();assert(JSON.parse(w.localStorage.getItem('solo-desk-v1')).tasks.length===before+14,'no duplicate example');
$('#lessonNext').click();assert($('#lessonTitle').textContent==='Set the goal and keep the context','next lesson');
$('#lessonDone').checked=true;$('#lessonDone').dispatchEvent(new w.Event('change'));
assert(JSON.parse(w.localStorage.getItem('solo-desk-v1')).carnivalTutorial.completed.includes(1),'progress saved');
w.document.querySelector('[data-lesson="4"]').click();$('#lessonAction').click();
assert($('#search').value==='#volunteers','guided filter');
assert(w.document.querySelectorAll('.task').length===2,'volunteer filter results');
w.document.querySelector('[data-lesson="7"]').click();$('#lessonAction').click();
assert($('#taskName').value==='Reconcile income, thank helpers and review','wrap-up editor');
$('#taskDialog').close();$('#tutorialClose').click();assert($('#tutorial').hidden,'tutorial closes');
dom.window.close();
console.log('PASS: task controls, persistence, search, timer, tutorial navigation, additive example, duplicate prevention, progress, guided filters and wrap-up');
